import assert from 'node:assert/strict';
import fs from 'node:fs/promises';
import {openApp} from './support/app-fixture.mjs';import {layout,position,defaultCamera} from '../dist/map.mjs';
import {unproject} from '../dist/core.mjs';
const app=await openApp(),{get,flush,savedConfig,loadConfig}=app;
const html=await fs.readFile(new URL('../dist/index.html',import.meta.url),'utf8');
assert.match(html,/<label class="field">地圖投影<select id="projection">/);
assert.doesNotMatch(html,/advancedWorld|進階全球設定|陸地底色|生物群系|陸域生態區界線/);
const original=await savedConfig();
assert.equal(original.settings.projection,'mercator');
for(const projection of ['equalEarth','robinson','mercator']){
 get('projection').value=projection;
 await get('projection').emit('change');
 assert.equal((await savedConfig()).settings.projection,projection);
}
const legacy=structuredClone(original);
Object.assign(legacy.settings,{projection:'robinson',worldCenter:170,ecologyTheme:'biomes',ecoregions:true,legendBiomes:true});
legacy.camera=defaultCamera(legacy.settings,legacy.referenceBounds,170);
legacy.legendEdits={biomes:{title:'Legacy biomes'},taxa:{font:15}};
await loadConfig(legacy);
let cfg=await savedConfig();
assert.equal(cfg.settings.projection,'robinson');
assert.ok(Math.abs(unproject(cfg.camera.x,cfg.camera.y)[0]-170)<1e-6);
for(const key of ['ecologyTheme','ecoregions','legendBiomes'])assert.ok(!(key in cfg.settings));
assert.deepEqual(cfg.legendEdits,{taxa:{font:15}});
assert.equal(get('terrain').disabled,false);
const pacific={...cfg.camera};
const frame=layout(cfg.settings);
const greenland=[[-73,78],[-42,60],[-11.5,81]].map(q=>position(...q,pacific,frame,cfg.settings));
assert.ok(greenland.every(([x,y])=>x>frame.x&&x<frame.x+frame.w&&y>frame.y&&y<frame.y+frame.h),'Greenland fits inside the map frame');
assert.ok(greenland.every(([x])=>x>frame.x+frame.w/2),'Greenland stays on the same side of the Pacific map');
await get('zoomIn').emit('click');assert.ok((await savedConfig()).camera.zoom>cfg.camera.zoom);await get('resetBtn').emit('click');assert.deepEqual((await savedConfig()).camera,pacific,'Reset retains Pacific choice');
const p=layout(cfg.settings),anchor=[160,-10],start=position(...anchor,cfg.camera,p,cfg.settings),map=get('map');await map.emit('pointerdown',{clientX:start[0],clientY:start[1],pointerId:1});await map.emit('pointermove',{clientX:start[0]+45,clientY:start[1]+15,pointerId:1});await map.emit('pointerup');cfg=await savedConfig();const moved=position(...anchor,cfg.camera,p,cfg.settings);assert.ok(Math.hypot(moved[0]-start[0]-45,moved[1]-start[1]-15)<.1);await get('resetBtn').emit('click');
cfg=await savedConfig();
await get('saveProject').emit('click');
const project=await app.downloads.at(-1).blob.text();
await loadConfig(original);
get('projectFile').files=[app.file('world.tbm.json',project)];
await get('projectFile').emit('change');
await flush();
assert.deepEqual(await savedConfig(),cfg,'Projection is restored from a complete project');
for(const [key,value] of [['projection','invalid'],['worldCenter',23]]){
 const bad=structuredClone(cfg);bad.settings[key]=value;
 await loadConfig(bad);
 assert.deepEqual(await savedConfig(),cfg);
}
const old=structuredClone(original);delete old.settings.projection;delete old.settings.worldCenter;
await loadConfig(old);
assert.equal((await savedConfig()).settings.projection,'mercator');
console.log('PASS: direct projection control, legacy Pacific view, drag/zoom, project settings and retired ecology migration');
