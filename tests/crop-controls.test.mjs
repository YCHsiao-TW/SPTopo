import assert from 'node:assert/strict';
import {openApp} from './support/app-fixture.mjs';
const {get,savedConfig,loadConfig,flush}=await openApp();
const before=await savedConfig();
await get('cropStart').emit('click');
await get('map').emit('pointerdown',{clientX:300,clientY:200,pointerId:1});
await get('map').emit('pointermove',{clientX:650,clientY:700,pointerId:1});
await get('map').emit('pointerup',{pointerId:1});
assert.equal(get('cropApply').disabled,false);
await get('cropCancel').emit('click');assert.deepEqual(await savedConfig(),before);
await get('cropStart').emit('click');
await get('map').emit('pointerdown',{clientX:300,clientY:200,pointerId:1});
await get('map').emit('pointermove',{clientX:650,clientY:700,pointerId:1});
await get('map').emit('pointerup',{pointerId:1});
await get('cropApply').emit('click');await flush();
const cropped=await savedConfig();assert.notEqual(cropped.settings.pageHeight,before.settings.pageHeight);assert.equal(get('region').value,'custom');assert.equal(get('cropActions').hidden,true);
await loadConfig(cropped);assert.deepEqual(await savedConfig(),cropped);
console.log('PASS: rectangle crop cancel, apply, aspect adjustment and settings persistence');
