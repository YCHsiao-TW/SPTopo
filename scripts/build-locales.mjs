import fs from 'node:fs';
const root=new URL('../',import.meta.url),keys=JSON.parse(fs.readFileSync(new URL('scripts/locale-keys.json',root),'utf8'));
const langs=['es','fr','de','ja','ko','ru','ar','hi'],packs=Object.fromEntries(langs.map(l=>[l,{}])),seen=new Set();
for(const line of fs.readFileSync(new URL('scripts/locale-additions.tsv',root),'utf8').trim().split('\n')){
 const [index,...values]=line.split('|'),i=Number(index);
 if(!Number.isInteger(i)||!keys[i]||seen.has(i)||values.length!==8||values.some(v=>!v.trim()))throw Error('Invalid locale row: '+index);
 seen.add(i);for(const [j,l]of langs.entries())packs[l][keys[i].trim()]=values[j].trim();
}
if(seen.size!==keys.length)throw Error(`Missing locale rows: ${keys.map((_,i)=>i).filter(i=>!seen.has(i)).join(',')}`);
fs.writeFileSync(new URL('dist/locale-extended.mjs',root),'// Generated by scripts/build-locales.mjs; edit scripts/locale-additions.tsv.\nexport const EXTENDED_TEXT='+JSON.stringify(packs,null,1)+';\n');
console.log(`Built ${keys.length} additional translations × ${langs.length} languages`);
